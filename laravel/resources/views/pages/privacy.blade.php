            <h2 id="adults">This Site Is for Adults</h2>

            <p>
                You must be 18 or older to donate or to apply to donate leaves. If you think someone under 18
                has given us information, email us and we'll delete it.
            </p>

            <h2 id="what-we-collect">What We Collect</h2>

            <p><strong>When you donate:</strong></p>

            <ul>
                <li>Your name, email address, and the amount and frequency you choose</li>
                <li>A record of each checkout you start, even if you don't finish paying</li>
                <li>
                    From Stripe, our payment processor: records of your payments, recurring donations, refunds,
                    and Stripe's fees
                </li>
            </ul>

            <p>You enter your card or bank details on Stripe's own page. They never reach our servers.</p>

            <p><strong>When you apply to donate leaves:</strong></p>

            <ul>
                <li>Your name, email address, phone number, and address</li>
                <li>
                    Drop-off or pickup, how many bags, when they'll be ready, how you heard about us, and any
                    questions you ask
                </li>
                <li>
                    Notes of our emails, texts, and calls with you about your leaves, such as the date and what
                    was said, so nobody slips through the cracks
                </li>
            </ul>

            <p>
                We're also moving our leaf program's records from past years, kept in spreadsheets, into our
                website.
            </p>

            <p>
                <strong>When a form doesn't go through:</strong> we save what you typed into the donate or leaf
                form the moment you send it, even if there's an error. We also save the error shown and your
                browser and device type. This lets us follow up if something went wrong.
            </p>

            <p><strong>When you visit:</strong></p>

            <ul>
                <li>
                    Two cookies that make forms and sign-in work: a session cookie and a security token.
                    Cloudflare, which protects our site, may also set its own cookies to tell people apart from
                    bots. We use no analytics, advertising, or tracking cookies or scripts.
                </li>
                <li>
                    Your IP address and browser type, stored with your session for two hours, and used to limit
                    how often a form can be sent
                </li>
                <li>
                    Access logs of each request to our site, kept for 90 days to protect it from abuse. They
                    hold your IP address, the page, the time, and the details your browser sends with each
                    request, such as its type and the page you came from.
                </li>
                <li>Error logs, kept for 30 days</li>
            </ul>

            <p>
                Our fonts are hosted on our own servers. Our forms check for bots with a small calculation your
                browser does, instead of a third-party CAPTCHA.
            </p>

            <h2 id="how-we-use-it">How We Use It</h2>

            <ul>
                <li>To process donations and send receipts</li>
                <li>To coordinate leaf drop-offs and pickups</li>
                <li>To answer your questions</li>
                <li>To research, measure, and report on our restoration work, as described below</li>
                <li>To prevent fraud and abuse</li>
            </ul>

            <h2 id="email-and-texts">Email and Texts</h2>

            <ul>
                <li>We email a receipt for every payment.</li>
                <li>
                    We reply when you contact us, and we email or text you about your leaf drop-off or pickup.
                    A person sends these, one at a time.
                </li>
                <li>
                    Stripe emails you a sign-in link when you manage a recurring donation, and lets you know if
                    a payment fails or your card is expiring.
                </li>
                <li>
                    We don't have a mailing list yet. If we start one, you'll join only by choosing to, and
                    every email will have an unsubscribe link. Donating or applying won't sign you up.
                </li>
            </ul>

            <h2 id="what-we-share">What We Share</h2>

            <p>
                We never sell your information. We don't share it with advertisers, data brokers, or map
                services such as Google Maps or Apple Maps. When we map pickup addresses, we do it on our own
                servers.
            </p>

            <p>These services run parts of our site and see only what they need for their job:</p>

            <ul>
                <li>
                    <a href="https://stripe.com/privacy" target="_blank" rel="noopener noreferrer">Stripe</a>:
                    payments and recurring donations
                </li>
                <li>
                    <a href="https://www.vultr.com/legal/privacy/" target="_blank" rel="noopener noreferrer">Vultr</a>:
                    our servers and their backups, in the United States
                </li>
                <li>
                    <a href="https://ahasend.com/privacy" target="_blank" rel="noopener noreferrer">AhaSend</a>:
                    delivering our emails
                </li>
                <li>
                    <a href="https://proton.me/legal/privacy" target="_blank" rel="noopener noreferrer">Proton Mail</a>:
                    our contact@wildland.eco inbox
                </li>
                <li>
                    <a href="https://www.cloudflare.com/privacypolicy/" target="_blank" rel="noopener noreferrer">Cloudflare</a>:
                    protects our site from attacks and speeds it up. Every visit passes through Cloudflare's
                    network, which sees your IP address and what you send to our site.
                </li>
            </ul>

            <p>
                We study our program records, such as dates, general areas, bag counts, and timestamped photos,
                to measure and improve our restoration work. Grant programs ask for this information in many
                forms, and new uses come up as our research grows, so we can't list every one in advance.
            </p>

            <p>
                What we share outside Wildland Ecotech never identifies you. It includes totals, such as bags of
                leaves collected or volunteer hours. For leaf donations, it also includes the general area your
                leaves came from, like "South-East Fort Collins", when we received them, how many bags you gave,
                and photos of the bags. These may appear in grant applications and reports, in our research, on
                our website and social media, and in our flyers, zines, and brochures. We remove precise location
                data from photos before sharing them.
            </p>

            <p>
                We never publish your name, address, phone number, or email address, and we don't name donors
                without asking first. We may share information when the law requires it.
            </p>

            <h2 id="how-long-we-keep-it">How Long We Keep It</h2>

            <ul>
                <li><strong>Donation records:</strong> permanently, for accounting and taxes. These can't be deleted.</li>
                <li>
                    <strong>Leaf applications, notes, and forms that didn't go through:</strong> until you ask us
                    to delete them.
                </li>
                <li>
                    <strong>Sessions:</strong> two hours. <strong>Access logs:</strong> 90 days.
                    <strong>Error logs:</strong> 30 days.
                </li>
                <li>
                    <strong>Backups:</strong> our servers are backed up weekly, and each backup is kept for one
                    month. Information you ask us to delete is gone from our backups within about a month.
                </li>
            </ul>

