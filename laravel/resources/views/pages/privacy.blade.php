            <h2 id="who-we-are">Who We Are</h2>

            <p>
                Wildland Ecotech (legally Wildland Ecology Technologies) is a 501(c)(3) nonprofit, EIN
                33-3738514, at 242 Linden Street, Fort Collins, CO 80524. This policy covers our website, the
