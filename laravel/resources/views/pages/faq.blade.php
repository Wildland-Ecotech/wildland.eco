            <details class="faq-item" id="how-it-began">
                <summary>How did Wildland Ecotech begin?</summary>

                <div class="prose">
                    <p>
                        Wildland Ecotech's origin comes from a lived relationship with forest ecosystems in Colorado.
                        Growing up on her grandparents' forest land fostered an early, direct connection to living
                        systems for Founder and Director Rachel Shelton: time spent in the woods, learning from the
                        land, and experiencing nature as a relational system rather than a backdrop. As her life
                        shifted toward indoor, technology-focused work, that connection gradually faded. In 2020,
                        during the Cameron Peak Fire, everything changed. Standing in Bellvue, Colorado as ash fell
                        across the porch during the uncertainty of the pandemic made ecological crisis immediate and
                        personal. Climate change was no longer abstract; it was visible, embodied, and unfolding in
                        real time. That moment became the catalyst for building a restoration practice rooted in
                        action rather than observation.
                    </p>

                    <p>
                        Since then, Wildland Ecotech has focused on post-wildfire watershed recovery in Colorado,
                        particularly within the Bellvue burn scar of the 2012 High Park Fire. Historically, this
                        landscape functioned as a connected montane watershed with wet meadows, riparian corridors,
                        beaver-influenced hydrology, and soils capable of holding and slowly releasing water. Today,
                        much of that system has been disrupted by high-severity fire effects, resulting in
                        hydrophobic soils, increased surface runoff, channel incision, reduced groundwater recharge,
                        and the loss of distributed wetland function. The landscape that once slowed and stored water
                        now often moves it rapidly downhill, intensifying erosion, downstream sedimentation, and
                        drought and wildfire vulnerability.
                    </p>

                    <p>
                        Wildland Ecotech's restoration approach is designed to reverse these hydrological failures
                        through nature-based infrastructure, using man-made technology for ecological good. Across
                        Colorado burn scars spanning more than 1,000 acres, we have constructed over 70 beaver dam
                        analogs (BDAs), along with additional water retention structures that reintroduce the
                        physical processes of wetland formation. These structures slow water movement, reconnect
                        floodplains, raise local water tables, and support sediment deposition and vegetative
                        recovery, rebuilding the conditions necessary for resilient, fire-adapted wetland ecosystems.
                    </p>
                </div>
            </details>

            <details class="faq-item" id="achievements">
                <summary>What has Wildland Ecotech achieved?</summary>

                <div class="prose">
                    <p>
                        Since its founding, Wildland Ecotech has restored degraded ecosystems through science-based,
                        community-driven conservation initiatives. The organization has mobilized volunteers to
                        construct more than 70 beaver dam analogs, improve watershed resilience, restore native
                        habitat, and mitigate wildfire impacts across Colorado. Since 2020, Wildland Ecotech's
                        restoration efforts have helped sequester hundreds of tons of CO₂ while enhancing ecosystem
                        resilience and biodiversity. By combining ecological restoration with environmental education
                        and emerging technologies such as drone mapping and environmental monitoring, Wildland Ecotech
                        advances practical, scalable solutions that improve ecosystem health, strengthen community
                        stewardship, and build resilience to climate change.
                    </p>
                </div>
            </details>

