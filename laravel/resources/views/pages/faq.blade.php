                <summary>What does Wildland Ecotech do?</summary>

                <div class="prose">
                    <p>
                        Wildland Ecotech is a 501(c)(3) nonprofit restoring land scarred by wildfire and pollution.
                        As a community-based environmental education and land restoration nonprofit dedicated to
                        cultivating reciprocal relationships between people, land, and water, we work at the
                        intersection of ecological restoration, youth STEM education, and food justice, with a
                        particular focus on landscapes impacted by wildfire, drought, and ecological disruption.
                    </p>

                    <p>
                        In Colorado, we build beaver dam analogs and water catchment structures across 1,000+ acres
                        of burn scar, planting trees and reducing wildfire risk. In New York, we steward recovering
                        wetlands near a Superfund site. Since 2020 we've sequestered hundreds of tons of CO₂.
                        Current and future initiatives include drone-based ecological surveys, LiDAR-informed terrain
                        modeling, and 3D water flow simulation to better understand watershed dynamics and scale
                        restoration strategies.
                    </p>

                    <p>
                        Our work is rooted in hands-on service, community collaboration, and ecological science,
                        including keystone species-informed restoration practices, such as beaver-based water
                        retention. We believe that healing land and supporting human communities are inseparable
                        processes, and that education, stewardship, and shared responsibility are essential to
                        long-term resilience.
                    </p>
                </div>
            </details>

